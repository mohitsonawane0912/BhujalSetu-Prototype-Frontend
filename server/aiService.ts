import { GoogleGenAI } from '@google/genai';
import { config } from './config';

export interface AiAdviceRequest {
  villageName?: string;
  aquiferType?: string;
  currentDepthMeters?: number;
  baselineDepthMeters?: number;
  changeMeters?: number;
  extractionLiters?: number;
  rechargeLiters?: number;
  netBalanceM3?: number;
  rainfallMm?: number;
  activeAlerts?: string[];
  recentObservations?: string[];
}

export interface AiAdviceResponse {
  success: boolean;
  source: 'gemini' | 'rule_based_fallback';
  status: 'configured' | 'unconfigured' | 'error';
  advisory: string;
  recommendedAction: string;
  criticalNotice?: string;
  disclaimer: string;
}

export async function generateGroundwaterAdvice(
  data: AiAdviceRequest
): Promise<AiAdviceResponse> {
  // If GEMINI_API_KEY is not configured
  if (!config.geminiApiKey || config.geminiApiKey === 'your_gemini_api_key_here') {
    return {
      success: true,
      source: 'rule_based_fallback',
      status: 'unconfigured',
      advisory:
        'Groundwater AI Advisor is running in deterministic rule mode because GEMINI_API_KEY is not set in .env.local. Based on current aquifer metrics, keep daytime extraction below the recharge threshold and inspect primary infiltration pits.',
      recommendedAction:
        'Verify recharge pit filter beds before the next rainfall cycle and avoid continuous multi-hour pumping.',
      disclaimer:
        'Notice: Deterministic baseline advisory. To activate Google Gemini live hydrological synthesis, set GEMINI_API_KEY in .env.local.',
    };
  }

  try {
    const ai = new GoogleGenAI({ apiKey: config.geminiApiKey });

    const systemPrompt = `You are the BhujalSetu Community Groundwater Intelligence Advisor.
Your role is to analyze verified groundwater telemetry, water balance calculations, and community reports to provide actionable, conservative advice for local water committees (Pani Samiti) and rural communities.

CRITICAL INVARIANTS:
1. YOU ARE AN ADVISOR, NOT THE SOURCE OF TRUTH. Do NOT invent, hallucinate, or alter any sensor measurements or hydrological values.
2. CLEARLY DISTINGUISH:
   - [MEASURED TELEMETRY]: Values directly captured by sensors; tabletop tank level is not groundwater depth.
   - [CALCULATED VALUES]: Water balance (inputs minus extraction), net cubic meters.
   - [ASSUMPTIONS]: Infiltration rates, runoff coefficients, seasonal baselines.
   - [RECOMMENDATIONS]: Specific community actions (pit de-silting, borewell rotation, leak repair).
3. Keep the advice concise, respectful of community participatory governance, and practically achievable.`;

    const userMessage = `Current Aquifer Data:
- Community / Village: ${data.villageName || 'Rampur Gram Panchayat'}
- Aquifer Type: ${data.aquiferType || 'Hard-rock semi-confined fractured granite/sandstone'}
- Measured Water Table Depth: ${data.currentDepthMeters ?? 'Unknown'} meters below surface
- Seasonal Baseline: ${data.baselineDepthMeters ?? 'Unknown'} meters
- Water Level Shift: ${data.changeMeters ?? '0'} meters
- Water Extracted: ${data.extractionLiters ?? '0'} Liters
- Water Recharged: ${data.rechargeLiters ?? '0'} Liters
- Net Water Balance: ${data.netBalanceM3 ?? '0'} m³
- Recent Rainfall: ${data.rainfallMm ?? '0'} mm
- Active Alerts: ${data.activeAlerts?.length ? data.activeAlerts.join('; ') : 'None'}
- Field Observations: ${data.recentObservations?.length ? data.recentObservations.join('; ') : 'None'}

Please provide:
1. A 2-3 sentence hydrological situation assessment.
2. One highest-priority immediate community intervention.
3. One preventative measure for the upcoming week.`;

    // 10 second timeout promise
    const timeoutPromise = new Promise<never>((_, reject) =>
      setTimeout(() => reject(new Error('Gemini API call timed out after 10 seconds')), 10000)
    );

    const apiCallPromise = ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: [
        {
          role: 'user',
          parts: [{ text: `${systemPrompt}\n\n${userMessage}` }],
        },
      ],
    });

    const response = await Promise.race([apiCallPromise, timeoutPromise]);
    const responseText = response.text || '';

    return {
      success: true,
      source: 'gemini',
      status: 'configured',
      advisory: responseText,
      recommendedAction: 'Coordinate Pani Samiti meeting to review extraction rosters based on this advisory.',
      disclaimer: 'Generated by Google Gemini based strictly on recorded telemetry and calculated balance.',
    };
  } catch (err: unknown) {
    const errorMsg = err instanceof Error ? err.message : String(err);
    console.error('[Gemini AI Service] Error during generation:', errorMsg);

    return {
      success: false,
      source: 'rule_based_fallback',
      status: 'error',
      advisory:
        'Groundwater AI Advisor encountered a connectivity or rate-limit issue with Gemini API. Fallback rule: Ensure extraction does not exceed recharge inflow; check borewell zones for night leaks.',
      recommendedAction: 'Continue following standard Pani Samiti rotational pumping schedules.',
      criticalNotice: `AI Service Notice: ${errorMsg}`,
      disclaimer: 'Fallback hydrological rule returned due to Gemini API temporary unavailability.',
    };
  }
}
